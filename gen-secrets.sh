#!/bin/bash
# Writes App/Sources/Kumo/Secrets.swift (git-ignored) from server/.env so the phone app signs in by itself.
cd "$(dirname "$0")" && source server/.env || exit 1
API_BASE="${KUMO_API%/api/graphql}"
printf '// generated by gen-secrets.sh from server/.env - do not commit\nenum BuiltIn { static let server = "%s"; static let user = "%s"; static let pass = "%s" }\n' "$API_BASE" "$KUMO_USER" "$KUMO_PASS" > App/Sources/Kumo/Secrets.swift
echo "Secrets.swift written for $API_BASE"
